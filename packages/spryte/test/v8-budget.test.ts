// @vitest-environment node
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

/**
 * V8 inlines a function into its caller only while its bytecode is at most 460 bytes, and stops inlining into one
 * caller after about 920 bytes in total. A sprite call it can't inline boxes its numbers on the heap, which cost
 * 2dbench's bunny scene about 4% (commit ec09e105). These limits keep the draw.sprite path inlinable.
 * They're V8 heuristics, not a contract: if a V8 upgrade moves them, re-measure before raising a limit.
 */
const LIMITS = [
  // Draw.sprite, found by the names it calls. Small, so a game's loop can inline it along with the backend.
  { name: "Draw.sprite", marker: "frameOf", max: 200 },
  { name: "WebGL2Backend.sprite", marker: "unitSrc", max: 460 },
  { name: "WebGL2Backend.write", marker: "u32", max: 460 },
];

const fixture = fileURLToPath(new URL("./v8/sprite-path.mjs", import.meta.url));
const built = existsSync(fileURLToPath(new URL("../dist/webgl2.js", import.meta.url)));

/** Bytecode length of each compiled function named `name`, with the identifiers in its constant pool. */
function bytecode(name: string): { length: number; pool: string }[] {
  const out = execFileSync(process.execPath, ["--print-bytecode", `--print-bytecode-filter=${name}`, fixture], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return out
    .split("[generated bytecode for function: ")
    .slice(1)
    .map((block) => ({ length: Number(/Bytecode length: (\d+)/.exec(block)?.[1] ?? Number.NaN), pool: block }));
}

describe.skipIf(!built)("V8 inlining budget of the sprite path (needs dist/: run tsc -b)", () => {
  it.each(LIMITS)("$name stays within $max bytes of bytecode", ({ name, marker, max }) => {
    const fn = name.split(".")[1] as string;
    const found = bytecode(fn).filter((b) => b.pool.includes(`#${marker}>`));
    expect(found, `${name} wasn't compiled, or no longer uses ${marker}: update this test's marker`).toHaveLength(1);
    expect(found[0]?.length).toBeLessThanOrEqual(max);
  });
});
