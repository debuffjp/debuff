// Regenerates what debuff ships from the glyphs in glyphs.mjs: packages/core/src/render/debuff-sans-data.ts
// and fonts/debuff-sans/debuff-sans.png (a 6x9 grid in sheet order, for Aseprite and other engines).
// `--check` exits 1 if they are stale. Font files for other apps (TTF, BDF) come from release.mjs.

import { readFileSync, writeFileSync } from "node:fs";
import { advanceOf, EXTRAS, H, ORDER, rowsOf, W } from "./glyphs.mjs";
import { png } from "./png.mjs";

const B32 = "0123456789abcdefghijklmnopqrstuv";

// Packed: per glyph, its advance (one digit, 0 for space) then 9 rows, each row a base-32 digit whose
// bit 4 is the leftmost pixel. 10 characters per glyph.
let packed = "";
const chars = [];
for (const ch of ORDER) {
  const rows = rowsOf(ch);
  packed += advanceOf(ch);
  for (const row of rows) {
    let bits = 0;
    for (let x = 0; x < 5; x++) if (row[x] === "#") bits |= 16 >> x;
    packed += B32[bits];
  }
  chars.push(rows);
}

const ts = `// Generated by fonts/debuff-sans/build.mjs. Do not edit; change the glyphs there.
/** debuff sans glyphs, printable ASCII then {@link DEBUFF_SANS_EXTRAS}: per glyph its advance, then 9 rows as base-32 bitmasks (bit 4 = left). */
export const DEBUFF_SANS =
  "${packed}";

/** The glyphs after printable ASCII, in order. */
export const DEBUFF_SANS_EXTRAS = "${Object.keys(EXTRAS).join("")}";
`;

// A plain PNG grid (white on transparent), so the font can be used outside debuff.
const sheet = png(W * chars.length, H, (x, y) => (chars[Math.floor(x / W)][y]?.[x % W] === "#" ? 0xffffffff : 0));

const outputs = [
  [new URL("../../packages/core/src/render/debuff-sans-data.ts", import.meta.url), Buffer.from(ts)],
  [new URL("./debuff-sans.png", import.meta.url), sheet],
];
const check = process.argv.includes("--check");
let stale = false;
for (const [url, data] of outputs) {
  let current;
  try {
    current = readFileSync(url);
  } catch {}
  if (current?.equals(data)) continue;
  if (check) {
    console.error(`stale: ${url.pathname} (run node fonts/debuff-sans/build.mjs)`);
    stale = true;
  } else writeFileSync(url, data);
}
if (stale) process.exit(1);
