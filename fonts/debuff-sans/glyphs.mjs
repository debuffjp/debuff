/** Every glyph in sheet order: printable ASCII, then the extras. */
export const ORDER = [...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)), ...Object.keys(EXTRAS)];

/** Rows of a glyph, padded to H. */
export function rowsOf(ch) {
  const rows = GLYPHS[ch] ?? EXTRAS[ch];
  if (!rows) throw new Error(`missing glyph ${JSON.stringify(ch)}`);
  if (rows.length > H || rows.some((r) => r.length > 5 || /[^.#]/.test(r))) throw new Error(`bad glyph ${JSON.stringify(ch)}`);
  return Array.from({ length: H }, (_, y) => rows[y] ?? "");
}

/** Pixels to advance: the widest row, 0 for an empty glyph (space). */
export const advanceOf = (ch) => Math.max(0, ...rowsOf(ch).map((r) => r.lastIndexOf("#") + 1));
