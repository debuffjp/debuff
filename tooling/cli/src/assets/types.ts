import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { CompiledManifest } from "./compile.js";

/** Where the generated asset types go; templates list it in tsconfig's `include`. */
export const ASSET_TYPES_FILE = ".debuff/assets.d.ts";

/** A declaration file that fills `@debuffjp/assets`'s `AssetRegistry`, so a misspelt asset id or group fails to compile. */
export function assetTypes(manifest: CompiledManifest): string {
  const rows = Object.entries(manifest.assets).map(
    ([id, a]) => `    ${JSON.stringify(id)}: { type: ${JSON.stringify(a.type)}; group: ${JSON.stringify(a.group ?? "default")} };`,
  );
  return [
    "// Generated by debuff from assets/. Don't edit: it is rewritten whenever assets/ changes.",
    'import "@debuffjp/assets";',
    "",
    'declare module "@debuffjp/assets" {',
    "  interface AssetRegistry {",
    ...rows,
    "  }",
    "}",
    "",
  ].join("\n");
}

/** Write the asset types under `root`, only when they changed, so editors and watchers don't churn. Returns whether it wrote. */
export function writeAssetTypes(root: string, manifest: CompiledManifest): boolean {
  const file = join(root, ASSET_TYPES_FILE);
  const text = assetTypes(manifest);
  if (existsSync(file) && readFileSync(file, "utf8") === text) return false;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
  return true;
}
